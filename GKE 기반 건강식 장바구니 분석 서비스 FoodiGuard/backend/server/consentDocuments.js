//   - 영양 기준 산출   : mobile/src/nutritionScoring.js (KDRIs 2025)
//
// 표시 순서는 배열 순서를 따른다.
//
// 연구 목적 이용(RESEARCH)은 여기 없다. user_consents 의 consent_type 에는 값이 남아 있지만
